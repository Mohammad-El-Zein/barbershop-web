/**
 * npm run api:generate
 *
 * Regenerates the typed API client types from the backend's OpenAPI spec:
 *   1. fetches the spec (default http://localhost:8080/v3/api-docs, or API_DOCS_URL)
 *   2. stores a snapshot in src/lib/api/openapi.json (reviewable in diffs)
 *   3. writes TypeScript types to src/lib/api/schema.d.ts (used by openapi-fetch)
 *
 * The backend must be running (docker compose -f infra/docker-compose.yml up -d).
 * Works on Windows, macOS and Linux (no shell variables needed).
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const url = process.env.API_DOCS_URL ?? "http://localhost:8080/v3/api-docs";
const outDir = resolve(root, "src/lib/api");

const res = await fetch(url).catch((e) => {
  console.error(`Could not reach ${url} — is the backend running?\n${e.message}`);
  process.exit(1);
});
if (!res.ok) {
  console.error(`${url} answered HTTP ${res.status}`);
  process.exit(1);
}
const spec = await res.json();
// the server URL depends on where the spec was fetched from — keep the snapshot stable
spec.servers = [{ url: "http://localhost:8080", description: "local backend" }];

await mkdir(outDir, { recursive: true });
await writeFile(resolve(outDir, "openapi.json"), JSON.stringify(spec, null, 2) + "\n");

const ast = await openapiTS(spec, { alphabetize: true });
const banner =
  "/**\n * GENERATED by `npm run api:generate` from the backend OpenAPI spec — do not edit.\n */\n\n";
await writeFile(resolve(outDir, "schema.d.ts"), banner + astToString(ast));

console.log(`API types generated from ${url}: ${Object.keys(spec.paths).length} paths, ` +
  `${Object.keys(spec.components?.schemas ?? {}).length} schemas → src/lib/api/schema.d.ts`);
